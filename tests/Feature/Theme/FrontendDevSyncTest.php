test('FrontendDevState mirrors theme dev state into project registry', function () {
    $themePath = frontendDevSyncThemeDir();
    $GLOBALS['__frontendDevSyncThemePath'] = $themePath;
    $projectRoot = dirname($themePath, 2);
    $registryPath = $projectRoot . '/.pinoox/dev.json';

    \Pinoox\Component\Template\Frontend\FrontendDevState::write(
        $themePath,
        viteUrl: 'http://127.0.0.1:5173',
        port: 5173,
        outDir: 'dist',
        projectRoot: $projectRoot,
    );

    expect(is_file($themePath . '/.pinoox/dev.json'))->toBeTrue()
        ->and(is_file($registryPath))->toBeTrue();

    $registry = json_decode((string) file_get_contents($registryPath), true);

    expect($registry['themes'] ?? [])->not->toBeEmpty();

    \Pinoox\Component\Template\Frontend\FrontendDevState::remove($themePath, $projectRoot);

    expect(is_file($themePath . '/.pinoox/dev.json'))->toBeFalse()
        ->and(is_file($registryPath))->toBeFalse();
});
