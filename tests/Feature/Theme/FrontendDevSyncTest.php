test('FrontendDevSync npmDevEnvironment injects VITE keys without writing env files', function () {
    $themePath = frontendDevSyncThemeDir();
    $GLOBALS['__frontendDevSyncThemePath'] = $themePath;

    file_put_contents($themePath . '/frontend.config.php', "<?php\n\nreturn ['stack' => 'vue'];\n");

    $config = FrontendConfig::forThemePath($themePath);
    $session = FrontendDevSession::fromOptions('com_demo_app', $config, '127.0.0.1', FRONTEND_DEV_SYNC_TEST_SERVE_PORT, 'com_demo_app', true);

    $npmEnv = FrontendDevSync::npmDevEnvironment($config, null, 'com_demo_app', $session, $themePath);

    expect($npmEnv['VITE_DEV_PORT'])->toBe((string) $session->vitePort)
        ->and($npmEnv['VITE_SERVER_URL'])->toBe('http://127.0.0.1:' . FRONTEND_DEV_SYNC_TEST_SERVE_PORT)
        ->and($npmEnv['VITE_DEV_SERVER'])->toBe($session->viteDevServerUrl())
        ->and(is_file($themePath . '/.env'))->toBeFalse()
        ->and(is_file($themePath . '/.env.local'))->toBeFalse();
});

