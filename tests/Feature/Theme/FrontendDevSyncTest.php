<?php

use Pinoox\Component\Template\Frontend\FrontendConfig;
use Pinoox\Component\Template\Frontend\FrontendDevSession;
use Pinoox\Component\Template\Frontend\FrontendDevSync;

const FRONTEND_DEV_SYNC_TEST_SERVE_PORT = 19800;

const FRONTEND_DEV_SYNC_ENV_KEYS = ['VITE_DEV_PORT', 'VITE_DEV', 'VITE_DEV_SERVER', 'VITE_DEV_FORCE'];

function frontendDevSyncEnvSnapshot(): array
{
    $snapshot = [];

    foreach (FRONTEND_DEV_SYNC_ENV_KEYS as $key) {
        $snapshot[$key] = $_ENV[$key] ?? null;
    }

    return $snapshot;
}

function frontendDevSyncEnvRestore(array $snapshot): void
{
    foreach ($snapshot as $key => $value) {
        if ($value === null) {
            unset($_ENV[$key], $_SERVER[$key]);
            putenv($key);
        } else {
            $_ENV[$key] = $value;
            $_SERVER[$key] = $value;
        }
    }
}

function frontendDevSyncThemeDir(): string
{
    // Mirror real apps/{pkg}/theme/{name} so dirname(dirname($theme)) is the app root.
    $appPath = sys_get_temp_dir() . '/pinoox-fe-sync-' . uniqid('', true);
    $themePath = $appPath . '/theme/default';
    mkdir($themePath, 0777, true);

    return $themePath;
}

function frontendDevSyncRemoveThemeDir(string $path): void
{
    if (!is_dir($path)) {
        return;
    }

    // Prefer removing the app root when the helper created …/theme/default.
    $normalized = rtrim(str_replace('\\', '/', $path), '/');
    if (str_ends_with($normalized, '/theme/default')) {
        $path = dirname($path, 2);
    }

    if (!is_dir($path)) {
        return;
    }

    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );

    foreach ($iterator as $item) {
        if ($item->isDir()) {
            @rmdir($item->getPathname());
        } else {
            @unlink($item->getPathname());
        }
    }

    @rmdir($path);
}

beforeEach(function () {
    $GLOBALS['__frontendDevSyncEnvSnapshot'] = frontendDevSyncEnvSnapshot();
});

afterEach(function () {
    if (isset($GLOBALS['__frontendDevSyncThemePath'])) {
        frontendDevSyncRemoveThemeDir($GLOBALS['__frontendDevSyncThemePath']);
        unset($GLOBALS['__frontendDevSyncThemePath']);
    }

    if (isset($GLOBALS['__frontendDevSyncEnvSnapshot'])) {
        frontendDevSyncEnvRestore($GLOBALS['__frontendDevSyncEnvSnapshot']);
        unset($GLOBALS['__frontendDevSyncEnvSnapshot']);
    }
});

test('FrontendDevSync sync leaves existing theme .env byte-for-byte unchanged', function () {
    $themePath = frontendDevSyncThemeDir();
    $GLOBALS['__frontendDevSyncThemePath'] = $themePath;

    $originalEnv = "MY_CUSTOM=stay\nENV_SERVER_SYNC=true\n";
    file_put_contents($themePath . '/frontend.config.php', "<?php\n\nreturn ['stack' => 'vue'];\n");
    file_put_contents($themePath . '/.env', $originalEnv);

    $config = FrontendConfig::forThemePath($themePath);
    $session = FrontendDevSession::fromOptions('com_demo_app', $config, '127.0.0.1', FRONTEND_DEV_SYNC_TEST_SERVE_PORT, 'com_demo_app', true);

    $result = FrontendDevSync::sync($themePath, $config, dirname(__DIR__, 3), $session, false, '.env.local');

    expect($result['env_autodev'])->toBeFalse()
        ->and($result['env_seeded'])->toBeFalse()
        ->and(file_get_contents($themePath . '/.env'))->toBe($originalEnv);
});

